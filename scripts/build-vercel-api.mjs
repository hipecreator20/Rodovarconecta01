import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { build } from 'esbuild';

const root = process.cwd();
const dataDir = path.join(root, 'data');

function collectJsonFiles(dir, relPrefix = '') {
  const entries = {};
  if (!fs.existsSync(dir)) return entries;
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = relPrefix ? `${relPrefix}/${item.name}` : item.name;
    const full = path.join(dir, item.name);
    if (item.isDirectory()) {
      Object.assign(entries, collectJsonFiles(full, rel));
    } else if (
      item.isFile() &&
      item.name.endsWith('.json') &&
      !item.name.includes('.backup') &&
      !item.name.includes('.tmp')
    ) {
      entries[rel] = fs.readFileSync(full, 'utf8');
    }
  }
  return entries;
}

const seedMap = collectJsonFiles(dataDir);
const compressedBase64 = zlib
  .gzipSync(Buffer.from(JSON.stringify(seedMap), 'utf8'))
  .toString('base64');

const seedFileContent = `// Auto-generated by scripts/build-vercel-api.mjs — do not edit manually
export const EMBEDDED_DATA_SEED_GZIP_B64 = ${JSON.stringify(compressedBase64)};
`;

fs.writeFileSync(path.join(root, 'src/server/embeddedDataSeed.ts'), seedFileContent, 'utf8');
console.log(
  `[build-vercel-api] Embedded ${Object.keys(seedMap).length} data JSON files (${Math.round(compressedBase64.length / 1024)} KB compressed).`
);

// Remove legacy api/index.ts if present so Vercel uses the pre-bundled api/index.js
const legacyTsEntry = path.join(root, 'api/index.ts');
if (fs.existsSync(legacyTsEntry)) {
  fs.unlinkSync(legacyTsEntry);
}

await build({
  entryPoints: [path.join(root, 'src/server/vercelEntry.ts')],
  outfile: path.join(root, 'api/index.js'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  packages: 'external',
  logLevel: 'info',
});

console.log('[build-vercel-api] Successfully bundled api/index.js for Vercel Serverless.');

